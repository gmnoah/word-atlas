import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true,channel:process.env.PREVIEW_BROWSER || 'chrome'});
try {
 const context = await browser.newContext();
 const page = await context.newPage();
 await page.goto('http://localhost:5188/#/explore?course=hanzi-starter');
 await page.locator('.hanzi-map-stop').first().getByRole('button',{name:'只读一读'}).click();
 await page.getByRole('heading',{name:'一个字，一个小发现'}).waitFor();
 await page.getByRole('button',{name:'看过啦，下一个'}).click();
 await page.getByRole('button',{name:'返回主题'}).click();
 await page.getByRole('button',{name:'结束体验'}).click();
 await page.getByRole('button',{name:'今日旅程'}).click();
 await page.getByRole('button',{name:/继续共读/}).waitFor();
 await page.getByRole('button',{name:'学习记录'}).click();
 await page.getByText('一起共读 1 次').waitFor();
 await page.getByText('查看主题足迹').click();
 assert.match(await page.locator('.course-theme-records li').first().innerText(), /看过 [1-9]\d* \/ /);
 await page.getByText('独立答对 0 次 · 提示后答对 0 次 · 家长一起答对 0 次').waitFor();
 await page.reload();
 await page.getByText('一起共读 1 次').waitFor();
 const record = await page.evaluate(() => JSON.parse(localStorage.getItem('word-atlas:v3:activity:learner-default:hanzi-starter')));
 assert.equal(Object.keys(record.sessions).length, 1);
 assert.deepEqual(Object.values(record.sessions)[0].answers, {});
 await page.getByRole('button',{name:'家长设置'}).click();
 await page.getByRole('button',{name:'新建学习者'}).click();
 await page.getByRole('button',{name:'设置好了'}).click();
 await page.getByText('还没有详细活动记录。之后的小课会在这里留下记录。').waitFor();
 await page.getByRole('button',{name:'家长设置'}).click();
 await page.getByLabel('选择学习者').selectOption('learner-default');
 await page.getByRole('button',{name:'设置好了'}).click();
 await page.getByText('一起共读 1 次').waitFor();
 console.log('汉字共读实际操作、保存、记录展示及刷新通过');
 await context.close();
 const english = await browser.newContext();
 await english.addInitScript(() => { Date.now = () => 1003; });
 const englishPage = await english.newPage();
 await englishPage.goto('http://localhost:5188/#/explore?course=primary-starter');
 await englishPage.getByRole('button',{name:'开始小课'}).first().click();
 for (let i = 0; i < 2; i++) await englishPage.getByRole('button',{name:'认识了，继续'}).click();
 const card = englishPage.locator('.preview-study-card.is-recall');
 await card.waitFor();
 assert.equal(await card.getAttribute('data-question-kind'), 'picture-word');
 const target = await card.getAttribute('data-content-id');
 await englishPage.locator(`[data-option-id="${target}"]`).click();
 await englishPage.getByText('找到了！').waitFor();
 await englishPage.getByRole('button',{name:'返回主题'}).click();
 await englishPage.getByRole('button',{name:'结束体验'}).click();
 await englishPage.getByRole('button',{name:'学习记录'}).click();
 await englishPage.getByText('独立答对 1 次 · 提示后答对 0 次 · 家长一起答对 0 次').waitFor();
 await englishPage.getByText('查看主题足迹').click();
 assert.match(await englishPage.locator('.course-theme-records li').first().innerText(), /看过 [1-9]\d* \/ /);
 await englishPage.reload();
 await englishPage.getByText('独立答对 1 次 · 提示后答对 0 次 · 家长一起答对 0 次').waitFor();
 console.log('英语实际答题、保存、记录展示及刷新通过');
 await english.close();
} finally { await browser.close(); }
