/** Use an isolated browser and a synthetic localStorage fixture. */
import assert from "node:assert/strict";
import { chromium } from "playwright";
import fs from "node:fs/promises";
const base = process.env.PREVIEW_URL || "http://localhost:5188/";
await fs.mkdir("output/preview-check", { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.PREVIEW_BROWSER || "chrome" });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`${base}#/explore`);
  await page.getByRole("heading", { name: "选择你的学习旅程" }).waitFor();
  await page.screenshot({ path: "output/preview-check/draft-entry-desktop.png", fullPage: true, animations: "disabled" });
  await page.locator('[data-course-id="primary-starter"]').getByRole("button", { name: "检查课程内容" }).click();
  await page.getByRole("heading", { name: "基础英语 · 内容清单" }).waitFor();
  await page.getByText("300 个词，可以逐条查看。").waitFor();
  await page.getByRole("navigation", { name: "草稿分页" }).getByRole("button", { name: "下一页" }).click();
  await page.getByText("第 2 / 15 页").waitFor();
  await page.getByRole("navigation", { name: "草稿分页" }).getByRole("button", { name: "上一页" }).click();
  await page.getByLabel("搜索草稿").fill("no-such-word-xyz");
  await page.getByText("没有找到匹配的内容，试试其他词。").waitFor();
  const saved = await page.evaluate(() => Object.fromEntries(Object.entries(localStorage).filter(([key]) => key.startsWith("word-atlas:"))));
  await page.getByLabel("搜索草稿").fill("apple");
  await page.getByRole("button", { name: "查看 apple 草稿" }).click();
  assert.equal(await page.locator(".draft-review-detail audio").count(), 1);
  assert.equal(await page.evaluate(async () => (await fetch(document.querySelector(".draft-review-detail audio").src)).status), 200);
  assert.ok(await page.evaluate(async () => { const audio = document.querySelector(".draft-review-detail audio"); audio.muted = true; await audio.play(); const duration = audio.duration; audio.pause(); return Number.isFinite(duration) && duration > 0; }));
  if (await page.getByRole("button", { name: "下一条" }).isEnabled()) await page.getByRole("button", { name: "下一条" }).click();
  await page.getByRole("button", { name: "返回学习空间" }).click();
  await page.locator('[data-course-id="hanzi-starter"]').getByRole("button", { name: "检查课程内容" }).click();
  await page.getByText("300 个字，可以逐条查看。").waitFor();
  await page.getByLabel("搜索草稿").fill("红");
  await page.getByRole("button", { name: "查看 红 草稿" }).click();
  await page.locator(".draft-review-detail img").waitFor();
  await page.waitForFunction(() => document.querySelector(".draft-review-detail img")?.naturalWidth > 0);
  assert.equal(await page.locator(".draft-review-detail audio").count(), 0);
  assert.equal(await page.evaluate(async () => (await fetch('/local/draft-review/media/hanzi/hanzi-u7238/word/../../other')).status), 404);
  await page.screenshot({ path: "output/preview-check/draft-desktop-dark.png", fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "切换到浅色" }).click();
  await page.screenshot({ path: "output/preview-check/draft-desktop-light.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.screenshot({ path: "output/preview-check/draft-mobile-light.png", fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "切换到深色" }).click();
  await page.screenshot({ path: "output/preview-check/draft-mobile-dark.png", fullPage: true, animations: "disabled" });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const after = await page.evaluate(() => Object.fromEntries(Object.entries(localStorage).filter(([key]) => key.startsWith("word-atlas:") && key !== "word-atlas:settings")));
  const beforeWithoutSettings = Object.fromEntries(Object.entries(saved).filter(([key]) => key !== "word-atlas:settings"));
  assert.deepEqual(after, beforeWithoutSettings, "reviewing does not change profiles or learning progress");
  assert.deepEqual(errors, []);
  console.log("Passed: both complete draft catalogs, search, media, local isolation, mobile and themes");
} finally { await browser.close(); }
